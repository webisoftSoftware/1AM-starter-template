#!/usr/bin/env node

import { createHash } from 'node:crypto';
import { execFileSync, spawnSync } from 'node:child_process';
import { mkdtempSync, readFileSync, rmSync, statSync, writeFileSync } from 'node:fs';
import { homedir, tmpdir } from 'node:os';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const SCRIPT_DIR = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(SCRIPT_DIR, '..');
const SOURCE_PATH = join(ROOT, 'contracts/proofSimulator.compact');
const OUTPUT_PATH = join(ROOT, 'contracts/managed/proofSimulator');
const DEFAULT_MIN_K = 6;
const DEFAULT_MAX_K = 20;
const ABSOLUTE_MAX_K = 25;

function parseArgs(argv) {
  const options = { minK: DEFAULT_MIN_K, maxK: DEFAULT_MAX_K, skipProvingKeys: false };
  for (let index = 0; index < argv.length; index += 1) {
    const argument = argv[index];
    if (argument === '--min-k') options.minK = Number(argv[++index]);
    else if (argument === '--max-k') options.maxK = Number(argv[++index]);
    else if (argument === '--skip-proving-keys') options.skipProvingKeys = true;
    else throw new Error(`Unknown argument: ${argument}`);
  }

  if (!Number.isInteger(options.minK) || !Number.isInteger(options.maxK)) {
    throw new Error('K bounds must be integers.');
  }
  if (options.minK < DEFAULT_MIN_K || options.maxK > ABSOLUTE_MAX_K || options.minK > options.maxK) {
    throw new Error(`Expected 6 <= min-k <= max-k <= ${ABSOLUTE_MAX_K}.`);
  }
  return options;
}

function circuitName(k) {
  return `probeK${String(k).padStart(2, '0')}`;
}

function inputLengthFor(k) {
  // `mix` emits two rows per vector element. This puts the row count just over
  // 2^(k - 1), selecting the requested 2^k proving domain.
  return 2 ** (k - 2);
}

function renderSource(minK, maxK) {
  const circuits = [];
  for (let k = minK; k <= maxK; k += 1) {
    const inputLength = inputLengthFor(k);
    circuits.push(`export circuit ${circuitName(k)}(seed: Vector<${inputLength}, Field>): [] {\n  lastValue = disclose(fold(mix, 0, seed));\n}`);
  }

  return `// Generated by scripts/generate-proof-simulator.mjs. Do not hand-edit.\npragma language_version 0.23;\n\nimport CompactStandardLibrary;\n\nexport ledger lastValue: Field;\n\nconstructor() {\n  lastValue = 0;\n}\n\ncircuit mix(accumulator: Field, value: Field): Field {\n  return accumulator * accumulator + value;\n}\n\n${circuits.join('\n\n')}\n`;
}

function run(command, args, options = {}) {
  if (options.capture) {
    const result = spawnSync(command, args, { cwd: ROOT, encoding: 'utf8' });
    if (result.status !== 0) {
      throw new Error(`${command} ${args.join(' ')} failed:\n${result.stdout || ''}${result.stderr || ''}`);
    }
    return `${result.stdout || ''}${result.stderr || ''}`;
  }
  return execFileSync(command, args, {
    cwd: ROOT,
    encoding: 'utf8',
    stdio: 'inherit',
  });
}

function compactBinaryPath() {
  const compactDirectory = process.env.COMPACT_DIRECTORY || resolve(homedir(), '.compact');
  return join(compactDirectory, 'versions/0.31.0', `${process.arch === 'arm64' ? 'aarch64' : 'x86_64'}-${process.platform === 'darwin' ? 'darwin' : 'linux'}`, 'zkir');
}

function mockCompile(zkirPath) {
  const output = run(compactBinaryPath(), ['mock-compile', zkirPath], { capture: true });
  const match = output.match(/\(k=(\d+), rows=(\d+)\)/);
  if (!match) throw new Error(`Could not parse zkir model output for ${zkirPath}: ${output}`);
  return { actualK: Number(match[1]), rows: Number(match[2]) };
}

function sha256(path) {
  return createHash('sha256').update(readFileSync(path)).digest('hex');
}

function artifactMetadata(path) {
  return { bytes: statSync(path).size, sha256: sha256(path) };
}

function assertGitLfs() {
  try {
    run('git', ['lfs', 'version'], { capture: true });
  } catch {
    throw new Error('Git LFS is required before generating the bundled proof simulator keys. Install Git LFS, run `git lfs install`, then retry.');
  }
}

function main() {
  const options = parseArgs(process.argv.slice(2));
  const source = renderSource(options.minK, options.maxK);
  writeFileSync(SOURCE_PATH, source);

  const calibrationDir = mkdtempSync(join(tmpdir(), 'midnight-proof-simulator-'));
  try {
    run('compact', [
      'compile', '+0.31.0', '--skip-zk', '--no-communications-commitment', SOURCE_PATH, calibrationDir,
    ]);

    const calibrated = [];
    for (let k = options.minK; k <= options.maxK; k += 1) {
      const name = circuitName(k);
      const model = mockCompile(join(calibrationDir, 'zkir', `${name}.zkir`));
      if (model.actualK !== k) {
        throw new Error(`${name} calibrated to k=${model.actualK}, expected k=${k}.`);
      }
      calibrated.push({ circuitId: name, targetK: k, actualK: model.actualK, rows: model.rows, inputLength: inputLengthFor(k) });
    }

    if (options.skipProvingKeys) {
      rmSync(OUTPUT_PATH, { recursive: true, force: true });
      run('compact', [
        'compile', '+0.31.0', '--skip-zk', '--no-communications-commitment', SOURCE_PATH, OUTPUT_PATH,
      ]);
      writeFileSync(join(OUTPUT_PATH, 'proof-simulator-manifest.json'), `${JSON.stringify({
        generatedAt: new Date().toISOString(),
        compilerVersion: '0.31.0',
        languageVersion: '0.23.0',
        runtimeVersion: '0.16.0',
        minK: options.minK,
        maxK: options.maxK,
        complete: false,
        circuits: calibrated,
      }, null, 2)}\n`);
      console.log('Calibration completed; proving keys were intentionally skipped.');
      return;
    }

    assertGitLfs();
    rmSync(OUTPUT_PATH, { recursive: true, force: true });
    run('compact', [
      'compile', '+0.31.0', '--no-communications-commitment', SOURCE_PATH, OUTPUT_PATH,
    ]);

    const circuits = calibrated.map((entry) => {
      const base = join(OUTPUT_PATH, 'keys', entry.circuitId);
      const zkirPath = join(OUTPUT_PATH, 'zkir', `${entry.circuitId}.bzkir`);
      return {
        ...entry,
        artifacts: {
          prover: artifactMetadata(`${base}.prover`),
          verifier: artifactMetadata(`${base}.verifier`),
          zkir: artifactMetadata(zkirPath),
        },
      };
    });

    const contractInfo = JSON.parse(readFileSync(join(OUTPUT_PATH, 'compiler/contract-info.json'), 'utf8'));
    writeFileSync(join(OUTPUT_PATH, 'proof-simulator-manifest.json'), `${JSON.stringify({
      generatedAt: new Date().toISOString(),
      compilerVersion: contractInfo['compiler-version'],
      languageVersion: contractInfo['language-version'],
      runtimeVersion: contractInfo['runtime-version'],
      minK: options.minK,
      maxK: options.maxK,
      complete: true,
      circuits,
    }, null, 2)}\n`);
  } finally {
    rmSync(calibrationDir, { recursive: true, force: true });
  }
}

main();
